// Write the gitignored .env.devnet the router and the walkthrough run with:
//
//   bun scripts/demo/make-env.ts            # create, or refresh public values while keeping generated secrets
//   bun scripts/demo/make-env.ts --rotate   # new APP_SECRET, ADMIN_TOKEN, router and facilitator relay keys
//
// Public values come from config/devnet.env.example. Secrets are produced here and written only to .env.devnet (mode
// 0600): APP_SECRET and ADMIN_TOKEN (random), the settlement, anchorer and slasher roles (the deployer keypair at
// SOLANA_KEYPAIR or ~/.config/solana/id.json, which holds every program authority on devnet), a router signing key and a
// facilitator relay key (fresh keypairs; the relay must hold no other role), and RECEIPT_SIGNING_KEY from the receipt
// signer recorded in deployments/devnet.secrets.json (so receipts verify against trellis_anchor's SignerSet). The script
// prints public keys only. A re-run keeps the RPC endpoint the file already names and every line added to it by hand.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { Keypair } from "@solana/web3.js";
import { loadSigner } from "../../src/solana/keys.ts";
import { loadSecrets } from "../devnet/lib.ts";
import { DATABASE_URL, ENV_EXAMPLE, ENV_FILE, envFileRpcUrl, handAddedLines, loadKeypair, parseEnvFile, pkcs8Base64FromSeed, rpcLabel, secretKeyBase58, writePrivateFile } from "./lib.ts";

const rotate = process.argv.includes("--rotate");
const example = parseEnvFile(ENV_EXAMPLE);
const current = rotate ? {} : parseEnvFile(ENV_FILE);
const keep = (name: string, make: () => string) => current[name] || make();

const deployer = loadKeypair();
const deployerSecret = secretKeyBase58(deployer);
const routerSecret = keep("ROUTER_PRIVATE_KEY", () => secretKeyBase58(Keypair.generate()));
const relaySecret = keep("FACILITATOR_RELAY_PRIVATE_KEY", () => secretKeyBase58(Keypair.generate()));
const secrets = loadSecrets();
const receiptKey = secrets.receiptSigner ? pkcs8Base64FromSeed(Uint8Array.from(secrets.receiptSigner.secretKey)) : current.RECEIPT_SIGNING_KEY ?? "";

const lines: string[] = [
  "# Generated by scripts/demo/make-env.ts. Gitignored: holds secrets for the devnet router. Never commit or share.",
  `# Public values follow config/devnet.env.example; re-run the script after that file changes.`,
  "",
  "# ---- Router ----",
  "TRELLIS_ENV=development",
  "HOST=127.0.0.1",
  "PORT=8787",
  "PUBLIC_BASE_URL=http://127.0.0.1:8787",
  `DATABASE_URL=${DATABASE_URL}`,
  "REDIS_URL=", // unset: in-process jobs, in-memory rate limits and cache
  `APP_SECRET=${keep("APP_SECRET", () => randomBytes(32).toString("hex"))}`,
  `ADMIN_TOKEN=${keep("ADMIN_TOKEN", () => randomBytes(24).toString("hex"))}`,
  "LOG_LEVEL=info",
  "ALLOW_DEV_ATTESTATION=true",
  "NEW_KEYS_PER_HOUR=1000",
  "",
  "# ---- Devnet (config/devnet.env.example) ----",
];
const skip = new Set(["FAUCET_ENABLED", "SOL_RPC_URL", "SOLANA_RPC_URL"]);
for (const [k, v] of Object.entries(example)) if (!skip.has(k)) lines.push(`${k}=${v}`);
// The endpoint already in .env.devnet stays (also across --rotate: it is the operator's, not a generated secret); only
// SOLANA_RPC_URL / DEVNET_RPC_URL in the environment replace it.
const url = envFileRpcUrl(process.env, parseEnvFile(ENV_FILE), example);
lines.push(`SOL_RPC_URL=${url}`, `SOLANA_RPC_URL=${url}`);
lines.push(
  "FAUCET_ENABLED=false", // the credits config names Circle's devnet USDC; its mint authority is not ours, so no faucet
  "",
  "# ---- Roles (devnet: the deployer keypair is every program authority) ----",
  `SETTLEMENT_PRIVATE_KEY=${deployerSecret}`,
  `ANCHORER_PRIVATE_KEY=${deployerSecret}`,
  `SLASHER_PRIVATE_KEY=${deployerSecret}`,
  `ROUTER_PRIVATE_KEY=${routerSecret}`, // tab payee and x402 relay; a key of its own so a tab's payer and payee differ
  "",
  "# ---- Per-call x402 (scheme exact): payments land in the router key's USDC account, the account tab closes pay ----",
  `X402_PAY_TO=${loadSigner(routerSecret).publicKey.toBase58()}`,
  "",
  "# ---- Hosted x402 facilitator (schemes exact and tab); the relay key only pays fees ----",
  "FACILITATOR_ENABLED=true",
  `FACILITATOR_RELAY_PRIVATE_KEY=${relaySecret}`,
  "",
  "# ---- Receipt signing key: trellis_anchor SignerSet.current_signer (deployments/devnet.secrets.json) ----",
  `RECEIPT_SIGNING_KEY=${receiptKey}`,
  "",
);
// The attested gateway's API key (scripts/demo/private-ai.ts --call) is supplied by the operator, not generated here:
// carry it over unchanged, also across --rotate. Never printed.
const gatewayKey = parseEnvFile(ENV_FILE).PRIVATE_AI_API_KEY;
if (gatewayKey) lines.push("# ---- Attested gateway API key (scripts/demo/private-ai.ts --call) ----", `PRIVATE_AI_API_KEY=${gatewayKey}`, "");
// Whatever was added to the file by hand (settings this script does not write, values parked in a comment) is carried
// over unchanged, so a re-run never loses it.
const written = new Set(lines.map((l) => /^([A-Za-z_][A-Za-z0-9_]*)=/.exec(l)?.[1]).filter((n): n is string => !!n));
const kept = existsSync(ENV_FILE) ? handAddedLines(readFileSync(ENV_FILE, "utf8"), written) : [];
if (kept.length) lines.push("# ---- Added by hand (kept across re-runs) ----", ...kept, "");
writePrivateFile(ENV_FILE, lines.join("\n"));

const addr = (secret: string) => loadSigner(secret).publicKey.toBase58();
console.log(`${existsSync(ENV_FILE) ? "wrote" : "created"} ${ENV_FILE} (mode 0600)`);
console.log(`  rpc                 ${rpcLabel(url)}`);
console.log(`  deployer / roles    ${deployer.publicKey.toBase58()}  (settlement, anchorer, slasher)`);
console.log(`  router signing key  ${addr(routerSecret)}  (tab payee)`);
console.log(`  facilitator relay   ${addr(relaySecret)}`);
console.log(`  receipt signer      ${secrets.receiptSigner?.publicKey ?? "(none: deployments/devnet.secrets.json has no receiptSigner; the router will use a rotating key that the chain does not name)"}`);
console.log(`  database            ${DATABASE_URL}`);
